package JAVA_DSA.Variables;

public class variables {
    public static void main(String[] args) {
        byte b = 8;
        System.out.println(b);
        char ch = 'a';
        System.out.println(ch);
        boolean var = false;
        System.out.println(var);
        float f = 10;
        System.out.println(f);
        double d = 10.5;
        System.out.println(d);
    }
}
